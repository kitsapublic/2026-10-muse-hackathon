import AxeBuilder from "@axe-core/playwright";
import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";

test.skip(process.env.ELIGIBILITY_LAB_RECORDED_BROWSER !== "1", "requires public recordings");

test("guided recorded story: evidence, 19 → 29/23/37, review export, Back, reload and accessibility", async ({ page, request }, info) => {
  const mutations: string[] = [], siteRequests: string[] = [];
  page.on("request", r => { if (r.url().includes("/v1/sites/")) siteRequests.push(r.url()); });
  page.on("request", r => { if (r.method() === "POST" && r.url().endsWith("/v1/jobs")) mutations.push(r.url()); });
  await page.goto("/");
  await expect(page.getByRole("heading", { level:1 })).toHaveText("Simulate Clinical Trials");
  await expect(page.getByText("Patient 011", { exact:true })).toBeVisible();
  await expect(page.locator(".rail-context .elab-mode")).toHaveText("Recorded model");
  const axe = async () => expect((await new AxeBuilder({page}).withTags(["wcag2a","wcag2aa","wcag21aa"]).analyze()).violations).toEqual([]);
  await axe();
  await page.screenshot({path:info.outputPath("01-question.png")});
  await page.getByRole("button", {name:"Read the patient’s EHR →"}).click();
  await expect(page.locator(".trace-card")).toBeVisible();
  await expect(page.locator(".trace-card .note").first()).toBeVisible();
  await expect(page.locator(".evidence-context")).toContainText("Viewing these responses makes no new calls");
  expect(mutations).toHaveLength(0);
  await page.screenshot({path:info.outputPath("02-muse.png"),fullPage:true});
  await axe();
  await page.getByRole("button", {name:"Evaluate the draft criteria →"}).click();
  await expect(page.getByRole("radio", {name:/Recorded model/})).toBeChecked();
  await expect(page.getByRole("radio", {name:/Live model/})).toBeDisabled();
  await page.getByRole("button", {name:"Evaluate eligibility",exact:true}).dblclick();
  await expect(page.locator(".outcomes [data-classification=passing] dd")).toHaveText("19 / 100");
  expect(mutations).toHaveLength(1);
  const baselineId = new URL(page.url()).searchParams.get("baseline");
  const baseline = await (await request.get(`/v1/jobs/${baselineId}/report.json`)).json();
  expect(baseline.costs.this_job.requests).toBe(0);
  expect(baseline.costs.reused.source_settled_microusd).toBe(645200);
  await expect(page.locator(".cohort-grid button")).toHaveCount(100);
  await page.getByRole("button", {name:"Inspect unresolved eligibility"}).click();
  await expect(page.locator(".patient-evidence .note").first()).toBeVisible();
  const patientId = new URL(page.url()).searchParams.get("patient");
  await page.reload();
  await expect(page.locator(`.cohort-grid button[aria-pressed=true]`)).toHaveAttribute("aria-label", new RegExp(patientId!));
  await page.getByRole("button", {name:"Patient evidence",exact:true}).click();
  await expect(page.locator(".patient-evidence")).toContainText(patientId!);
  await page.getByRole("button", {name:"Close inspector"}).click();
  await page.screenshot({path:info.outputPath("03-baseline.png"),fullPage:true});
  await page.getByRole("button", {name:"Optimize eligibility criteria →"}).click();
  const ids: string[] = [];
  for (const [label, count, anchor] of [["Age limit: 75 → 80 years",29,"Not eligible"],["Prior systemic regimens: 2 → 3",23,"Not eligible"],["Age 80 + up to 3 prior regimens",37,"Eligible"]] as const) {
    await page.getByRole("button", {name:new RegExp(label.replace("+", "\\+"))}).click();
    await page.getByRole("button", {name:"Run selected scenario"}).click();
    await expect(page.locator(".outcomes [data-classification=passing] dd")).toHaveText(`${count} / 100`);
    await expect(page.locator(".anchor-transition strong").last()).toHaveText(anchor);
    ids.push(new URL(page.url()).searchParams.get("scenario")!);
  }
  expect(mutations).toHaveLength(4);
  await page.getByRole("button", {name:"Compare the eligible populations →"}).click();
  await expect(page.getByLabel("Patients newly qualifying with both changes")).toHaveText(/10need the age change\+4need the treatment change\+4need both changes/);
  await expect(page.locator(".impact-story")).toContainText("24 to 30");
  await axe();
  await page.screenshot({path:info.outputPath("05-evidence.png"),fullPage:true});
  await page.getByRole("button", {name:"Execution",exact:true}).click();
  await expect(page.locator(".run-metrics")).toContainText("New model requests0");
  await expect(page.locator(".run-metrics")).toContainText("$0.6452");
  await page.getByRole("button", {name:"Review the proposed criteria →"}).click();
  await expect(page.getByRole("navigation", {name:"Story progress"}).getByRole("button")).toHaveCount(6);
  await expect(page.getByRole("button", {name:"Export review package ↓"})).toBeEnabled();
  await expect(page.locator(".technical-section")).toBeVisible();
  expect(siteRequests).toHaveLength(0);
  await axe();
  await page.screenshot({path:info.outputPath("06-review.png"),fullPage:true});
  const downloaded = page.waitForEvent("download");
  await page.getByRole("button", {name:"Export review package ↓"}).click();
  const review = JSON.parse(readFileSync((await (await downloaded).path())!, "utf8"));
  expect(review.scenario.counts).toEqual({passing:37,failing:33,unresolved:30,total:100});
  expect(review.baseline.job_id).toBe(baselineId);
  expect(review.scenario.job_id).toBe(ids[2]);
  expect(review.unresolved).toHaveLength(30);
  expect(review).not.toHaveProperty("site_planning");
  const both = await (await request.get(`/v1/jobs/${ids[2]}/report.json`)).json();
  expect(both.costs.this_job.requests).toBe(0);
  expect(both.result.patients.find((p: {patient_id:string})=>p.patient_id === "ELX-D-011").classification).toBe("passing");
  const wasFailing = new Set(baseline.result.patients.filter((p:{classification:string})=>p.classification === "failing").map((p:{patient_id:string})=>p.patient_id));
  expect(both.result.patients.filter((p:{patient_id:string;classification:string})=>p.classification === "unresolved" && wasFailing.has(p.patient_id))).toHaveLength(6);
  await page.reload();
  await expect(page.getByRole("heading", {level:1})).toHaveText("Take evidence-backed eligibility criteria into protocol review.");
  await page.goBack();
  await expect(page.getByRole("heading", {level:1})).toHaveText("Measure how each eligibility change affects the population.");
  expect(mutations).toHaveLength(4);
  await page.setViewportSize({width:390,height:844});
  await page.emulateMedia({reducedMotion:"reduce"});
  await page.getByRole("button", {name:"01 Design the eligibility criteria"}).click();
  await expect(page.getByRole("heading", {level:1})).toBeFocused();
  await axe();
  await page.screenshot({path:info.outputPath("mobile-question.png"),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(mutations).toHaveLength(4);
});
